function redistLines(redistribute) {
  const order = ["connected", "bgp", "ospf", "rip", "static", "kernel"];
  return order.filter((k) => redistribute[k]).map((k) => `redistribute ${k}`);
}

function buildRipBlock(device) {
  const rip = device.routing.rip;
  if (!rip.enabled) return "";
  const nets = rip.networks
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const forced = parseCidrList(rip.forceAnnounce);
  const lines = [
    "router rip",
    ...nets.map((n) => `network ${n}`),
    ...redistLines(rip.redistribute),
    ...forced.map((n) => `route ${n}`),
    "!",
  ];
  return lines.join("\n") + "\n";
}

// Top-level FRR static routes (owned by zebra, so "redistribute static" can pick them up),
// as opposed to plain kernel "ip route add" shell commands.
function buildStaticRouteLines(device) {
  return device.staticRoutes
    .filter((r) => r.declareInFrr && r.destination && r.via)
    .map((r) => `ip route ${r.destination} ${r.via}`);
}

function buildOspfBlock(device) {
  const ospf = device.routing.ospf;
  if (!ospf.enabled) return "";
  const ifaceBlocks = [];
  device.interfaces.forEach((iface, idx) => {
    const cfg = ospf.perInterface[idx];
    if (cfg && cfg.cost) {
      ifaceBlocks.push(`interface ${ethName(idx)}\nospf cost ${cfg.cost}\n`);
    }
  });
  const manualNetworks = ospf.manualNetworks
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  let networkLines;
  if (manualNetworks.length) {
    networkLines = manualNetworks.map((l) => `    network ${l}`);
  } else {
    networkLines = [];
    device.interfaces.forEach((iface, idx) => {
      const cfg = ospf.perInterface[idx];
      if (cfg && cfg.area !== "" && cfg.area !== undefined && cfg.area !== null && iface.ip) {
        const cidr = networkCidr(iface.ip, iface.cidr);
        if (cidr) networkLines.push(`    network ${cidr} area ${cfg.area}`);
      }
    });
  }
  const stubLines = parseCidrList(ospf.stubAreas).map((a) => `area ${a} stub`);
  const lines = [
    ...ifaceBlocks,
    "router ospf",
    ...networkLines,
    ...redistLines(ospf.redistribute).map((l) => "    " + l),
    ...(stubLines.length ? ["", ...stubLines] : []),
    "!",
  ];
  return lines.join("\n") + "\n";
}

function buildBgpBlock(device, model) {
  const bgp = device.routing.bgp;
  if (!bgp.enabled) return "";
  const lines = [];
  lines.push("!");
  lines.push("!  BGP CONFIGURATION");
  lines.push("!");
  if (bgp.debug) {
    lines.push("debug bgp keepalives");
    lines.push("debug bgp updates in");
    lines.push("debug bgp updates out");
    lines.push("!");
  }
  lines.push(`router bgp ${device.as}`);
  if (bgp.noEbgpRequiresPolicy) lines.push("no bgp ebgp-requires-policy");
  if (bgp.noNetworkImportCheck) lines.push("no bgp network import-check");
  lines.push("!");
  lines.push("! NEIGHBORS");
  lines.push("!");
  const routeMaps = [];
  const accessLists = [];
  const prefixLists = [];
  for (const n of bgp.neighbors) {
    if (!n.ip || !n.remoteAs) continue;
    lines.push(`neighbor ${n.ip} remote-as ${n.remoteAs}`);
    if (n.description) lines.push(`neighbor ${n.ip} description ${n.description}`);
    if (n.routeMapOut) {
      const rmName = `rm_${n.ip.replace(/\./g, "_")}_out`;
      lines.push(`neighbor ${n.ip} route-map ${rmName} out`);
      const matchPrefixes = parseCidrList(n.routeMapOutMatch);
      let alName = null;
      if (matchPrefixes.length) {
        alName = `al_${n.ip.replace(/\./g, "_")}_out`;
        accessLists.push({ name: alName, prefixes: matchPrefixes });
      }
      routeMaps.push({ name: rmName, match: alName, body: [`    set metric ${n.metric || 20}`] });
    }
    if (n.routeMapIn) {
      const rmName = `rm_${n.ip.replace(/\./g, "_")}_in`;
      lines.push(`neighbor ${n.ip} route-map ${rmName} in`);
      const matchPrefixes = parseCidrList(n.routeMapInMatch);
      let alName = null;
      if (matchPrefixes.length) {
        alName = `al_${n.ip.replace(/\./g, "_")}_in`;
        accessLists.push({ name: alName, prefixes: matchPrefixes });
      }
      routeMaps.push({ name: rmName, match: alName, body: [`    set local-preference ${n.localPref || 150}`] });
    }
    if (n.prefixListIn && n.prefixListIn.enabled) {
      const plName = `pl_${n.ip.replace(/\./g, "_")}_in`;
      lines.push(`neighbor ${n.ip} prefix-list ${plName} in`);
      prefixLists.push({ name: plName, mode: n.prefixListIn.mode || "deny", prefixes: parseCidrList(n.prefixListIn.prefixes) });
    }
    if (n.prefixListOut && n.prefixListOut.enabled) {
      const plName = `pl_${n.ip.replace(/\./g, "_")}_out`;
      lines.push(`neighbor ${n.ip} prefix-list ${plName} out`);
      prefixLists.push({ name: plName, mode: n.prefixListOut.mode || "deny", prefixes: parseCidrList(n.prefixListOut.prefixes) });
    }
  }
  lines.push("!");
  lines.push("! NETWORKS");
  lines.push("!");
  const nets = bgp.networks
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  for (const n of nets) lines.push(`network ${n}`);
  for (const r of redistLines(bgp.redistribute)) lines.push(r);
  if (routeMaps.length) {
    lines.push("!");
    lines.push("! ROUTING PREFERENCES");
    lines.push("!");
    for (const rm of routeMaps) {
      lines.push(`route-map ${rm.name} permit 10`);
      if (rm.match) lines.push(`    match ip address ${rm.match}`);
      lines.push(...rm.body);
      // With a match condition, non-matching routes need an unconditional catch-all clause,
      // otherwise the route-map's implicit trailing "deny" would drop them entirely.
      if (rm.match) lines.push(`route-map ${rm.name} permit 20`);
    }
  }
  if (accessLists.length) {
    lines.push("!");
    lines.push("! ACCESS LISTS");
    lines.push("!");
    for (const al of accessLists) {
      for (const p of al.prefixes) lines.push(`access-list ${al.name} permit ${p}`);
    }
  }
  if (prefixLists.length) {
    lines.push("!");
    lines.push("! PREFIX LISTS");
    lines.push("!");
    for (const pl of prefixLists) {
      if (pl.mode === "permit") {
        // Allow-list: only the listed prefixes are announced/accepted, everything else is implicitly denied.
        // Use "any" as one of the entries for an unconditional permit-any (e.g. towards a customer).
        for (const p of pl.prefixes) lines.push(`ip prefix-list ${pl.name} permit ${p}`);
      } else {
        // Block-list: the listed prefixes are blocked, everything else is allowed.
        for (const p of pl.prefixes) lines.push(`ip prefix-list ${pl.name} deny ${p}`);
        lines.push(`ip prefix-list ${pl.name} permit any`);
      }
    }
  }
  return lines.join("\n") + "\n";
}

// Spine/leaf datacenter fabric: BGP unnumbered (interface peer-group) EVPN underlay+overlay,
// written to its own etc/frr/bgpd.conf instead of the integrated frr.conf, matching the
// "patchwork" exam pattern.
function buildBgpdConfFabric(device) {
  const bgp = device.routing.bgp;
  const fabricIfaces = device.interfaces
    .map((iface, idx) => idx)
    .filter((idx) => bgp.fabricInterfaces[idx]);

  const lines = [
    "hostname frr",
    "password frr",
    "enable password frr",
    "",
    `router bgp ${device.as}`,
    " timers bgp 3 9",
  ];
  if (bgp.routerId) lines.push(` bgp router-id ${bgp.routerId}`);
  lines.push(" no bgp ebgp-requires-policy");
  lines.push(" bgp bestpath as-path multipath-relax");
  lines.push("");
  lines.push("neighbor TOR peer-group");
  lines.push(" neighbor TOR remote-as external");
  lines.push(" neighbor TOR advertisement-interval 0");
  lines.push(" neighbor TOR timers connect 10");
  for (const idx of fabricIfaces) {
    lines.push(` neighbor ${ethName(idx)} interface peer-group TOR`);
  }
  lines.push("");
  lines.push("address-family ipv4 unicast");
  lines.push("  neighbor TOR activate");
  if (bgp.fabricRedistributeLoopback) lines.push("  redistribute connected route-map LOOPBACKS");
  lines.push("  maximum-paths 64");
  lines.push("exit-address-family");
  lines.push("");
  lines.push("address-family l2vpn evpn");
  lines.push("  neighbor TOR activate");
  if (bgp.fabricAdvertiseAllVni) lines.push("  advertise-all-vni");
  lines.push("exit-address-family");
  if (bgp.fabricRedistributeLoopback) {
    lines.push("");
    lines.push("route-map LOOPBACKS permit 10");
    lines.push("  match interface lo");
  }
  return lines.join("\n") + "\n";
}

function buildFrrConf(device, model) {
  const parts = [];
  const staticLines = buildStaticRouteLines(device);
  if (staticLines.length) parts.push(staticLines.join("\n") + "\n");
  const rip = buildRipBlock(device);
  if (rip) parts.push(rip);
  const ospf = buildOspfBlock(device);
  if (ospf) parts.push(ospf);
  parts.push("!\nlog file /var/log/frr/frr.log\n");
  const bgp = buildBgpBlock(device, model);
  if (bgp) parts.push(bgp);
  if (device.customFrrConf && device.customFrrConf.trim()) {
    parts.push("!\n! CUSTOM\n!\n" + device.customFrrConf.trim() + "\n");
  }
  return parts.join("\n");
}

function frrEnabled(device) {
  return (
    device.routing.rip.enabled ||
    device.routing.ospf.enabled ||
    device.routing.bgp.enabled ||
    (device.customFrrConf && device.customFrrConf.trim()) ||
    device.staticRoutes.some((r) => r.declareInFrr && r.destination && r.via)
  );
}

function buildVtepCommands(device) {
  const vtep = device.vtep;
  const entries = (vtep.entries || []).filter((e) => e.vni && e.vlan);
  if (!vtep.enabled || !vtep.loopbackIp || !entries.length) return [];
  const brName = `br${entries[0].vlan}`;
  const trunkIfaces = parseCidrList(vtep.trunkIfaces)
    .map(Number)
    .filter((n) => !Number.isNaN(n));
  const lines = [
    "# Create loopback",
    `ip address add ${vtep.loopbackIp}/32 dev lo`,
    `ip route add ${vtep.loopbackIp}/32 dev lo`,
    "",
    "# Setting up VXLAN interfaces",
  ];
  for (const e of entries) {
    lines.push(`ip link add vtep${e.vni} type vxlan id ${e.vni} dev lo dstport 4789 local ${vtep.loopbackIp} nolearning`);
  }
  lines.push("");
  lines.push("# Creating the companion bridge");
  lines.push(`ip link add ${brName} type bridge`);
  lines.push(`ip link set ${brName} addrgenmode none`);
  lines.push("");
  lines.push("# Attach interfaces to the bridge");
  for (const e of entries) {
    lines.push(`ip link set dev vtep${e.vni} master ${brName} addrgenmode none`);
    lines.push(`ip link set vtep${e.vni} type bridge_slave neigh_suppress on learning off`);
  }
  for (const idx of trunkIfaces) {
    lines.push(`ip link set dev ${ethName(idx)} master ${brName}`);
  }
  lines.push("");
  lines.push("# Enable bridge VLANs");
  lines.push(`ip link set dev ${brName} type bridge vlan_filtering 1`);
  for (const e of entries) {
    lines.push(`bridge vlan add vid ${e.vlan} dev vtep${e.vni} pvid untagged`);
  }
  if (trunkIfaces.length) lines.push("");
  for (const idx of trunkIfaces) {
    for (const e of entries) lines.push(`bridge vlan add vid ${e.vlan} dev ${ethName(idx)}`);
    lines.push("");
  }
  lines.push("# Enable interfaces");
  for (const e of entries) lines.push(`ip link set up dev vtep${e.vni}`);
  lines.push(`ip link set up dev ${brName}`);
  return lines;
}

function buildBridgeCommands(device) {
  const bridge = device.bridge;
  const vlans = parseCidrList(bridge.vlans)
    .map(Number)
    .filter((n) => !Number.isNaN(n));
  if (!bridge.enabled || !vlans.length || !device.interfaces.length) return [];
  const brName = `br${vlans[0]}`;
  const lines = ["# Creating the bridge", `ip link add ${brName} type bridge`, "", "# Attach interfaces to the bridge"];
  device.interfaces.forEach((iface, idx) => {
    lines.push(`ip link set dev ${ethName(idx)} master ${brName}`);
  });
  lines.push("");
  lines.push("# Enable bridge vlans");
  lines.push(`ip link set dev ${brName} type bridge vlan_filtering 1`);
  device.interfaces.forEach((iface, idx) => {
    const accessVlan = bridge.portVlan[idx];
    if (accessVlan !== undefined && accessVlan !== "" && accessVlan !== null) {
      lines.push(`bridge vlan add vid ${accessVlan} dev ${ethName(idx)} pvid untagged`);
    } else {
      for (const v of vlans) lines.push(`bridge vlan add vid ${v} dev ${ethName(idx)}`);
    }
  });
  lines.push(`ip link set up dev ${brName}`);
  return lines;
}

function buildStartup(device, model) {
  const lines = [];

  const vtepLines = buildVtepCommands(device);
  if (vtepLines.length) {
    lines.push(...vtepLines);
    lines.push("");
  }
  const bridgeLines = buildBridgeCommands(device);
  if (bridgeLines.length) {
    lines.push(...bridgeLines);
    lines.push("");
  }

  const vtepTrunkIfaces = new Set(
    parseCidrList(device.vtep.trunkIfaces)
      .map(Number)
      .filter((n) => !Number.isNaN(n))
  );
  device.interfaces.forEach((iface, idx) => {
    if (device.bridge.enabled) return; // bridge members carry no L3 address
    if (device.vtep.enabled && vtepTrunkIfaces.has(idx)) return; // VXLAN trunk member
    if (iface.ip) {
      lines.push(`ip address add ${iface.ip}/${iface.cidr} dev ${ethName(idx)}`);
    }
  });
  for (const r of device.staticRoutes) {
    if (!r.destination || !r.via || r.declareInFrr) continue; // declareInFrr routes are set via frr.conf instead, so zebra owns them
    const devPart = r.iface !== "" && r.iface !== undefined && r.iface !== null ? ` dev ${ethName(Number(r.iface))}` : "";
    lines.push(`ip route add ${r.destination} via ${r.via}${devPart}`);
  }
  if (device.defaultRoute.enabled && device.defaultRoute.via) {
    const devPart =
      device.defaultRoute.iface !== "" && device.defaultRoute.iface !== undefined && device.defaultRoute.iface !== null
        ? ` dev ${ethName(Number(device.defaultRoute.iface))}`
        : "";
    lines.push(`ip route add default via ${device.defaultRoute.via}${devPart}`);
  }

  if (device.nat.enabled) {
    lines.push("");
    if (device.nat.enableForwarding) {
      lines.push("sysctl -w net.ipv4.ip_forward=1");
    }
    if (device.nat.masqueradeIface !== "" && device.nat.masqueradeIface !== undefined && device.nat.masqueradeIface !== null) {
      lines.push(`iptables --table nat --append POSTROUTING --out-interface ${ethName(Number(device.nat.masqueradeIface))} --jump MASQUERADE`);
    }
    for (const rule of device.nat.dnatRules) {
      if (!rule.destIp || !rule.dport) continue;
      const proto = rule.proto || "tcp";
      const targets = rule.targets.filter((t) => t.ip && t.port);
      if (targets.length === 1) {
        lines.push(
          `iptables --table nat --append PREROUTING --destination ${rule.destIp} -p ${proto} --dport ${rule.dport} --jump DNAT --to-destination ${targets[0].ip}:${targets[0].port}`
        );
      } else if (targets.length > 1) {
        // even split across targets using the "statistic" random match, like the load-balancer exam pattern
        targets.forEach((t, i) => {
          const remaining = targets.length - i;
          const prob = t.probability || (1 / remaining).toFixed(2);
          if (i < targets.length - 1) {
            lines.push(
              `iptables --table nat --append PREROUTING --destination ${rule.destIp} -p ${proto} --dport ${rule.dport} --match statistic --mode random --probability ${prob} --jump DNAT --to-destination ${t.ip}:${t.port}`
            );
          } else {
            lines.push(
              `iptables --table nat --append PREROUTING --destination ${rule.destIp} -p ${proto} --dport ${rule.dport} --jump DNAT --to-destination ${t.ip}:${t.port}`
            );
          }
        });
      }
    }
  }

  if (device.customStartup && device.customStartup.trim()) {
    lines.push("");
    lines.push(device.customStartup.trim());
  }

  const services = [];
  if (frrEnabled(device)) services.push("systemctl start frr");
  if (device.dns.role !== "none") services.push("systemctl start named");
  if (device.webserver.enabled) services.push("systemctl start apache2");
  if (services.length) {
    lines.push("");
    for (const s of services) lines.push(s);
  }

  // trim any leading/trailing blank lines, keep single blank separators
  return lines.join("\n").replace(/^\n+/, "").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}

function buildBindFiles(device, model) {
  const files = {};
  const dns = device.dns;
  if (dns.role === "none") return files;

  if (dns.role === "root") {
    files["etc/bind/named.conf"] = `include "/etc/bind/named.conf.options";\n\nzone "." {\n    type master;\n    file "/etc/bind/db.root";\n};\n`;
    files["etc/bind/named.conf.options"] = `options {\n    directory "/var/cache/bind";\n};\n`;
    const selfIp = device.interfaces[0] ? device.interfaces[0].ip : "";
    const lines = [
      "$TTL 60000",
      `@ IN SOA ${dns.hostname} root.${dns.hostname} (`,
      "    2024010100 ; serial",
      "    28800 ;  refresh",
      "    14400 ; retry",
      "    3600000 ; expire",
      "    0 ; negative cache ttl",
      ")",
      "",
      `@                  IN   NS   ${dns.hostname}`,
      `${dns.hostname}       IN    A   ${selfIp}`,
      "",
    ];
    for (const d of dns.delegations) {
      if (!d.subdomain || !d.nsName) continue;
      lines.push(`${d.subdomain}.               IN   NS   ${d.nsName}`);
      if (d.nsIp) lines.push(`${d.nsName}           IN    A   ${d.nsIp}`);
    }
    files["etc/bind/db.root"] = lines.join("\n") + "\n";
  }

  if (dns.role === "authoritative") {
    files["etc/bind/named.conf"] = [
      `include "/etc/bind/named.conf.options";`,
      "",
      `zone "." {`,
      `    type hint;`,
      `    file "/etc/bind/db.root";`,
      `};`,
      "",
      `zone "${dns.zone}" {`,
      `    type master;`,
      `    file "/etc/bind/db.${dns.zone}";`,
      `};`,
      "",
    ].join("\n");
    files["etc/bind/named.conf.options"] = `options {\n    directory "/var/cache/bind";\n};\n`;
    files["etc/bind/db.root"] = `.              IN   NS   ${dns.rootServer.name}\n${dns.rootServer.name}   IN    A   ${dns.rootServer.ip}\n`;
    const selfIp = device.interfaces[0] ? device.interfaces[0].ip : "";
    const zoneLines = [
      "$TTL\t60000",
      `@ IN SOA ${dns.hostname} root.${dns.hostname} (`,
      "\t2024010100 ; serial",
      "\t28800 ; refresh",
      "\t14400 ; retry",
      "\t360000 ; expire",
      "\t0 ; negative cache ttl",
      ")",
      "",
      `@\t\tIN\tNS\t${dns.hostname}`,
      `${dns.hostname}\tIN\t A\t${selfIp}`,
      "",
    ];
    for (const rec of dns.records) {
      if (!rec.name || !rec.ip) continue;
      zoneLines.push(`${rec.name}\tIN\t A\t${rec.ip}`);
    }
    files[`etc/bind/db.${dns.zone}`] = zoneLines.join("\n") + "\n";
  }

  if (dns.role === "resolver") {
    files["etc/bind/named.conf"] = [
      `include "/etc/bind/named.conf.options";`,
      "",
      `zone "." {`,
      `    type hint;`,
      `    file "/etc/bind/db.root";`,
      `};`,
      "",
    ].join("\n");
    const optLines = ["options {", `    directory "/var/cache/bind";`];
    if (dns.allowRecursion) optLines.push(`    allow-recursion { ${dns.allowRecursionCidr || "0.0.0.0/0"}; };`);
    optLines.push(`    dnssec-validation no;`);
    optLines.push("};");
    files["etc/bind/named.conf.options"] = optLines.join("\n") + "\n";
    files["etc/bind/db.root"] = `.                   IN  NS    ${dns.rootServer.name}\n${dns.rootServer.name}        IN  A     ${dns.rootServer.ip}\n`;
  }

  return files;
}

// Auto-fill root-server identity on authoritative/resolver devices by scanning the model for a 'root' device.
function resolveRootServerRef(device, model) {
  if (device.dns.rootServer.name && device.dns.rootServer.ip) return device.dns.rootServer;
  const rootDevice = model.devices.find((d) => d.dns.role === "root");
  if (rootDevice) {
    return {
      name: device.dns.rootServer.name || rootDevice.dns.hostname,
      ip: device.dns.rootServer.ip || (rootDevice.interfaces[0] ? rootDevice.interfaces[0].ip : ""),
    };
  }
  return device.dns.rootServer;
}

function generateLabConf(model) {
  const blocks = [];
  for (const d of model.devices) {
    if (!d.interfaces.length && !d.image && !(d.labConfExtra || "").trim()) continue;
    const lines = d.interfaces.map((iface, idx) => {
      const net = findNetwork(model, iface.network);
      return `${d.name}[${idx}]=${net ? net.name : "?"}`;
    });
    if (d.image && d.image.trim()) lines.push(`${d.name}[image]="${d.image.trim()}"`);
    const extra = (d.labConfExtra || "")
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean);
    for (const l of extra) lines.push(`${d.name}${l}`);
    if (lines.length) blocks.push(lines.join("\n"));
  }
  return blocks.join("\n\n") + "\n";
}

function generateFiles(model) {
  const files = {}; // relative path -> string content
  const labRoot = (model.labName || "lab").trim() || "lab";

  files[`${labRoot}/lab.conf`] = generateLabConf(model);

  for (const device of model.devices) {
    if (device.dns.role === "authoritative" || device.dns.role === "resolver") {
      device.dns._resolvedRoot = resolveRootServerRef(device, model);
    }
  }

  for (const device of model.devices) {
    const base = `${labRoot}/${device.name}`;
    const effectiveDevice = device.dns._resolvedRoot
      ? { ...device, dns: { ...device.dns, rootServer: device.dns._resolvedRoot } }
      : device;

    files[`${base}.startup`] = buildStartup(effectiveDevice, model);

    const isFabricBgp = effectiveDevice.routing.bgp.enabled && effectiveDevice.routing.bgp.mode === "fabric";
    if (frrEnabled(effectiveDevice)) {
      files[`${base}/etc/frr/daemons`] = FRR_DAEMONS_TEMPLATE(
        effectiveDevice.routing.bgp.enabled,
        effectiveDevice.routing.ospf.enabled,
        effectiveDevice.routing.rip.enabled
      );
      files[`${base}/etc/frr/vtysh.conf`] = "service integrated-vtysh-config\n";
      if (isFabricBgp) {
        files[`${base}/etc/frr/bgpd.conf`] = buildBgpdConfFabric(effectiveDevice);
      } else {
        files[`${base}/etc/frr/frr.conf`] = buildFrrConf(effectiveDevice, model);
      }
    }

    const bindFiles = buildBindFiles(effectiveDevice, model);
    for (const [path, content] of Object.entries(bindFiles)) {
      files[`${base}/${path}`] = content;
    }

    if (effectiveDevice.resolvConf.mode === "custom" && effectiveDevice.resolvConf.nameserver) {
      files[`${base}/etc/resolv.conf`] = `nameserver ${effectiveDevice.resolvConf.nameserver}\n`;
    } else if (effectiveDevice.resolvConf.mode === "empty") {
      files[`${base}/etc/resolv.conf`] = "";
    }

    if (effectiveDevice.webserver.enabled) {
      files[`${base}/var/www/html/index.html`] = effectiveDevice.webserver.html;
    }
  }

  for (const device of model.devices) delete device.dns._resolvedRoot;

  return files;
}
